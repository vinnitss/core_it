import pandas as pd
from modules.core.utils import engine, normalize_date, clean_money
from sqlalchemy import text


def load_and_clean_debts(file_path):
    df = pd.read_excel(file_path, sheet_name=0, dtype=str)
    df.columns = df.columns.str.strip().str.replace(' ', '_')

    # Удаляем пустые столбцы без заголовков (pandas называет их Unnamed: N)
    df = df.loc[:, ~df.columns.str.contains(r'^Unnamed', na=False)]

    column_mapping = {
        'Вид_задолженности': 'вид_задолженности',
        'Счет': 'счет',
        'Архивный_номер': 'архивный_номер',
        'Контрагент': 'контрагент',
        'Контрагент.ИНН': 'инн',
        'Контрагент.Состояние': 'состояние_контрагента',
        'Договор_контрагента.Код': 'договор_код',
        'Договор_контрагента.Вид_договора': 'договор_вид',
        'Договор_контрагента.Характер_договора': 'договор_характер',
        'Договор_контрагента': 'договор_наименование',
        'Проект': 'проект',
        'ЦФО': 'цфо',
        'Номер_документа': 'номер_документа',
        'Дата_документа': 'дата_документа',
        'Документ_расчетов': 'документ_расчетов',
        '!!!_Период_погашения_!!!': 'период_погашения',
        'Количество_дней_просрочки': 'дней_просрочки',
        'Сумма_взаиморасчетов_остаток': 'сумма_остаток',
    }
    df = df.rename(columns=column_mapping)

    # Оставляем только те столбцы, что есть в целевой таблице
    allowed = [
        'вид_задолженности', 'счет', 'архивный_номер', 'контрагент', 'инн',
        'состояние_контрагента', 'договор_код', 'договор_вид', 'договор_характер',
        'договор_наименование', 'проект', 'цфо', 'номер_документа',
        'дата_документа', 'документ_расчетов', 'период_погашения',
        'дней_просрочки', 'сумма_остаток',
    ]
    for col in allowed:
        if col not in df.columns:
            df[col] = None
    df = df[allowed]

    # Даты
    for col in ['дата_документа', 'период_погашения']:
        df[col] = df[col].apply(normalize_date)

    # Дни просрочки
    df['дней_просрочки'] = pd.to_numeric(df['дней_просрочки'], errors='coerce').fillna(0).astype(int)

    # Сумма
    df['сумма_остаток'] = df['сумма_остаток'].apply(clean_money)

    # Заполняем пустые текстовые значения
    text_cols = ['вид_задолженности', 'счет', 'архивный_номер', 'контрагент',
                 'инн', 'состояние_контрагента', 'договор_код', 'договор_вид',
                 'договор_характер', 'договор_наименование', 'проект', 'цфо',
                 'номер_документа', 'документ_расчетов']
    for col in text_cols:
        df[col] = df[col].fillna('')

    return df

def import_debts(file_path):
    """
    Полностью очищает таблицу debts и загружает новый файл.
    Вызывается ТОЛЬКО когда пользователь загрузил файл задолженности.
    Если файла нет — таблица не трогается.
    """
    df = load_and_clean_debts(file_path)
    with engine.connect() as conn:
        conn.execute(text("DELETE FROM debts;"))
        conn.commit()
    df.to_sql('debts', engine, if_exists='append', index=False, method='multi')
    return len(df)
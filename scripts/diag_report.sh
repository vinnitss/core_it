#!/bin/bash
# Использование: ./scripts/diag_report.sh НОМЕР_ЗАЯВКИ
NUM="${1:?Укажи номер заявки первым аргументом}"
docker exec -it report_db psql -U report_user -d report_db -v num="$NUM" -c "
SELECT
    номер_заявки, оплачена, статус_согласования, состояние_заявки,
    код, is_bezreestroviy, номер_рп, итоговый_статус_реестра, цфо,
    (оплачена = 'Нет')                                                              AS c1,
    (статус_согласования IN ('Согласовано ДФ','Согласовано руководителем ЦФО'))     AS c2,
    (состояние_заявки IS NULL OR состояние_заявки NOT IN ('Аннулирован','Подготовлен')) AS c3,
    (код IN ('СТГ-00','СТГ-2011-ОРГ','СТНГ-ПВД'))                                   AS c4a,
    (is_bezreestroviy = TRUE)                                                       AS c4b,
    (итоговый_статус_реестра = 'На согласовании')                                   AS c4c,
    (итоговый_статус_реестра ILIKE '%Принят%анком%')                                AS c4d
FROM v_applications_full
WHERE номер_заявки = :'num';
"